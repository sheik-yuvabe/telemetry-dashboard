// Run from the repository root. Credentials are read locally, never printed.
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');

function migrationSql() {
  const migrations = ['batch-2-migration.sql', 'student-summaries-migration.sql'];
  const body = migrations.map(name => {
    const sql = fs.readFileSync(path.join(root, 'supabase', name), 'utf8');
    if ((sql.match(/^begin;\s*$/gm) || []).length !== 1 || (sql.match(/^commit;\s*$/gm) || []).length !== 1) {
      throw new Error('Migration transaction boundaries changed; review the setup tool.');
    }
    return `-- Source: ${name}\n${sql.replace(/^begin;\s*$/m, '').replace(/^commit;\s*$/m, '')}`;
  }).join('\n');
  return `-- Generated by node tools/pilot-setup.cjs --prepare. Do not edit this copy.
-- Apply to the existing telemetry database, once, in Supabase SQL Editor.
-- Both migrations and preservation checks commit together, or all roll back.
begin;
set local lock_timeout = '10s';
set local statement_timeout = '120s';
lock table public.telemetry_reports in share row exclusive mode;
create temporary table pilot_reports_before on commit drop as
  select id, to_jsonb(r) as original from public.telemetry_reports r;
${body}
do $$
begin
  if (select count(*) from pilot_reports_before) <> (select count(*) from public.telemetry_reports) then
    raise exception 'Report count changed; rolling back';
  end if;
  if exists (
    select 1 from pilot_reports_before b
    left join public.telemetry_reports r on r.id=b.id
    where r.id is null or not (to_jsonb(r) @> b.original)
      or (not (b.original ? 'batch_id') and r.batch_id <> 'batch-1')
  ) then
    raise exception 'Existing report content or batch attribution changed; rolling back';
  end if;
  if exists (
    select 1 from public.telemetry_reports r
    left join public.batch_students s on s.batch_id=r.batch_id and s.student_id=r.student_id
    where s.student_id is null
  ) then
    raise exception 'Historical student enrollment missing; rolling back';
  end if;
end; $$;
notify pgrst, 'reload schema';
commit;
select batch_id, count(*) as preserved_reports from public.telemetry_reports group by batch_id order by batch_id;
`;
}

function prepare() {
  fs.writeFileSync(path.join(root, 'supabase', 'pilot-setup.sql'), migrationSql());
  console.log('Prepared supabase/pilot-setup.sql. No database changes made.');
}

async function check() {
  const url = process.env.SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error('Configure SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in .env.local.');
  const selections = {
    telemetry_reports: 'id,student_id,batch_id,project_id,report_date,created_at',
    batches: 'id,name,status', batch_students: 'batch_id,student_id,name,account_id',
    shared_accounts: 'id,name,capacity', student_projects: 'id,batch_id,student_id,name,status,progress',
    usage_events: 'batch_id,event_id,student_id,project_id,account_id,input_tokens,output_tokens,cached_input_tokens',
    student_summaries: 'scope_key,batch_id,student_id,scope,saved',
    student_summary_locks: 'batch_id,student_id,request_id,lease_until,last_attempt_at',
  };
  const headers = { apikey: key, Authorization: `Bearer ${key}`, Prefer: 'count=exact' };
  let ready = true;
  for (const [table, select] of Object.entries(selections)) {
    const response = await fetch(`${url.replace(/\/$/, '')}/rest/v1/${table}?select=${select}&limit=0`, { headers, signal: AbortSignal.timeout(15000) });
    const payload = await response.json();
    if (response.ok) console.log(`${table}: ready (${response.headers.get('content-range')?.split('/')[1] ?? '?'} rows)`);
    else { ready = false; console.log(`${table}: NOT READY (HTTP ${response.status}, ${payload.code || 'unknown'})`); }
  }
  for (const name of ['TELEMETRY_INGEST_TOKEN', 'SUPABASE_DB_URL', 'GEMINI_API_KEY', 'GEMINI_MODEL']) {
    console.log(`${name}: ${process.env[name] ? 'configured' : 'not configured'}`);
  }
  console.log(ready ? 'Required table columns are available. Complete the roster and authenticated app smoke test next.' : 'Database migration is still required.');
  console.log('This check reads schema/counts only; it does not test Gemini, SQL function permissions, or ingestion.');
  if (!ready) process.exitCode = 2;
}

function apply() {
  if (!process.env.SUPABASE_DB_URL) throw new Error('Add SUPABASE_DB_URL locally, or run supabase/pilot-setup.sql in Supabase SQL Editor.');
  let db;
  try { db = new URL(process.env.SUPABASE_DB_URL); } catch { throw new Error('Invalid SUPABASE_DB_URL.'); }
  const project = new URL(process.env.SUPABASE_URL).hostname.split('.')[0];
  if (!['postgres:', 'postgresql:'].includes(db.protocol)
      || !(db.hostname === `db.${project}.supabase.co`
        || (db.hostname.endsWith('.pooler.supabase.com') && decodeURIComponent(db.username) === `postgres.${project}`))) {
    throw new Error('Database connection must match the project configured in SUPABASE_URL.');
  }
  const sslmode = db.searchParams.get('sslmode') || 'require';
  if (!['require', 'verify-ca', 'verify-full'].includes(sslmode)) throw new Error('Database connection must use TLS.');
  if ([...db.searchParams.keys()].some(k => !['sslmode', 'sslrootcert'].includes(k))) throw new Error('Unsupported connection options; use a plain direct or session-pooler connection string.');
  const psql = process.env.PSQL_PATH || (process.platform === 'win32' ? 'C:\\Program Files\\PostgreSQL\\18\\bin\\psql.exe' : 'psql');
  const result = spawnSync(psql, ['-X', '-w', '-v', 'ON_ERROR_STOP=1'], {
    input: migrationSql(), encoding: 'utf8', windowsHide: true, timeout: 180000,
    env: { ...process.env, PGHOST: db.hostname, PGPORT: db.port || '5432',
      PGUSER: decodeURIComponent(db.username), PGPASSWORD: decodeURIComponent(db.password),
      PGDATABASE: decodeURIComponent(db.pathname.slice(1)), PGSSLMODE: sslmode,
      ...(db.searchParams.has('sslrootcert') ? { PGSSLROOTCERT: db.searchParams.get('sslrootcert') } : {}),
      PGCONNECT_TIMEOUT: '15', PGAPPNAME: 'yuvabe-pilot-setup' },
  });
  if (result.error || result.status !== 0) {
    // Do not echo connection errors, which can contain connection details.
    throw new Error('Migration did not complete successfully. Check connection details and access. Run --check to confirm database state.');
  }
  console.log(result.stdout.trim());
  console.log('Both migrations committed and existing report content was verified. Run --check next.');
}

if (require.main === module) {
  require('@next/env').loadEnvConfig(root, true, { info() {}, error() {} });
  const option = process.argv[2];
  Promise.resolve().then(() => {
    if (option === '--prepare') return prepare();
    if (option === '--check') return check();
    if (option === '--apply') return apply();
    throw new Error('Usage: node tools/pilot-setup.cjs --prepare | --check | --apply');
  }).catch(error => {
    console.error(error instanceof TypeError ? 'Connection failed. Check network access and local configuration.' : error.message);
    process.exitCode = 1;
  });
}
module.exports = { migrationSql };
